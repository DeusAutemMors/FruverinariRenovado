package com.jdc.fruverinari.model;

public class DiaPlanSemanal {

    private String dia;
    private String desayuno;
    private String desayunoTitulo;
    private String almuerzo;
    private String almuerzoTitulo;
    private String cena;
    private String cenaTitulo;

    public String getDia() {
        return dia;
    }

    public void setDia(String dia) {
        this.dia = dia;
    }

    public String getDesayuno() {
        return desayuno;
    }

    public void setDesayuno(String desayuno) {
        this.desayuno = desayuno;
    }

    public String getAlmuerzo() {
        return almuerzo;
    }

    public void setAlmuerzo(String almuerzo) {
        this.almuerzo = almuerzo;
    }

    public String getCena() {
        return cena;
    }

    public void setCena(String cena) {
        this.cena = cena;
    }

    public String getDesayunoTitulo() {
        return desayunoTitulo;
    }

    public void setDesayunoTitulo(String desayunoTitulo) {
        this.desayunoTitulo = desayunoTitulo;
    }

    public String getAlmuerzoTitulo() {
        return almuerzoTitulo;
    }

    public void setAlmuerzoTitulo(String almuerzoTitulo) {
        this.almuerzoTitulo = almuerzoTitulo;
    }

    public String getCenaTitulo() {
        return cenaTitulo;
    }

    public void setCenaTitulo(String cenaTitulo) {
        this.cenaTitulo = cenaTitulo;
    }
}
